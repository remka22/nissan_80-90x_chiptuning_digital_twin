# в редакторе.
# ШАГ по-прежнему зашит числом сдвигов (три LSRA = деление на 8 по давлению,
# четыре = на 16 по оборотам) и маской остатка. Менять шаг данными нельзя — нужен
# либо цикл с переменным сдвигом, либо настоящее деление.
PBASE = 40   # начало оси давления, кПа. Значение ПИШЕТСЯ В ТАБЛИЦУ, код берёт оттуда.
PSTEP = 8    # шаг оси давления. ОБЯЗАН быть степенью двойки — номер столбца берётся
