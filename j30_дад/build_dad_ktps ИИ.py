def asm(org):
    lab={}; pc=org
    for l,op,a in PROG:
        if l: lab[l]=pc
        pc+=LEN[op]
    out=bytearray(); pc=org
    for l,op,a in PROG:
        nx=pc+LEN[op]
        if   op=="LDDe":  out+=bytes([0xFC,a>>8,a&0xFF])
        elif op=="SUBD#": out+=bytes([0x83,a>>8,a&0xFF])
        elif op=="BCC":
            r=lab[a]-nx; assert -128<=r<=127,("BCC %s %d"%(a,r)); out+=bytes([0x24,r&0xFF])
        elif op=="BNE":
            r=lab[a]-nx; assert -128<=r<=127,("BNE %s %d"%(a,r)); out+=bytes([0x26,r&0xFF])
        elif op=="JSRe":  out+=bytes([0xBD,a>>8,a&0xFF])
        elif op=="LDAB#": out+=bytes([0xC6,a&0xFF])
        elif op=="SUBBe": out+=bytes([0xF0,a>>8,a&0xFF])
        elif op=="STABd": out+=bytes([0xD7,a&0xFF])
        elif op=="LDXe":  out+=bytes([0xFE,a>>8,a&0xFF])
        elif op=="STXd":  out+=bytes([0xDF,a&0xFF])
        elif op=="STXe":  out+=bytes([0xFF,a>>8,a&0xFF])
        elif op=="LDXd":  out+=bytes([0xDE,a&0xFF])
        elif op=="LDAAe": out+=bytes([0xB6,a>>8,a&0xFF])
        elif op=="LDAAd": out+=bytes([0x96,a&0xFF])
        elif op=="STAAd": out+=bytes([0x97,a&0xFF])
        elif op=="LDABd": out+=bytes([0xD6,a&0xFF])
        elif op=="LDABe": out+=bytes([0xF6,a>>8,a&0xFF])
        elif op=="STDe":  out+=bytes([0xFD,a>>8,a&0xFF])
        elif op=="BMI":
            r=lab[a]-nx; assert -128<=r<=127,("BMI %s %d"%(a,r)); out+=bytes([0x2B,r&0xFF])
        elif op=="BRA":
            r=lab[a]-nx; assert -128<=r<=127,("BRA %s %d"%(a,r)); out+=bytes([0x20,r&0xFF])
        elif op=="SUBAe": out+=bytes([0xB0,a>>8,a&0xFF])
        elif op=="LDAA#": out+=bytes([0x86,a&0xFF])
        elif op=="ANDA#": out+=bytes([0x84,a&0xFF])
        elif op=="ORAA#": out+=bytes([0x8A,a&0xFF])
        elif op=="LDX#":  out+=bytes([0xCE,a>>8,a&0xFF])
        # --- добавлено 09.08.26 ---
        elif op=="TSTe":  out+=bytes([0x7D,a>>8,a&0xFF])
        elif op=="JMPe":  out+=bytes([0x7E,a>>8,a&0xFF])
        elif op=="LDD#":  out+=bytes([0xCC,a>>8,a&0xFF])
        elif op=="BEQ":
            r=lab[a]-nx; assert -128<=r<=127,("BEQ %s %d"%(a,r)); out+=bytes([0x27,r&0xFF])
        elif op=="BCS":
            r=lab[a]-nx; assert -128<=r<=127,("BCS %s %d"%(a,r)); out+=bytes([0x25,r&0xFF])
        elif op=="SUBA#": out+=bytes([0x80,a&0xFF])
        elif op=="CMPA#": out+=bytes([0x81,a&0xFF])
        elif op=="ANDB#": out+=bytes([0xC4,a&0xFF])
        elif op=="ADCA#": out+=bytes([0x89,a&0xFF])
        elif op=="CMPAx": out+=bytes([0xA1,a&0xFF])
        elif op=="LDAAx": out+=bytes([0xA6,a&0xFF])
        elif op=="LDABx": out+=bytes([0xE6,a&0xFF])
        elif op=="SUBBd": out+=bytes([0xD0,a&0xFF])
        elif op=="ADDBd": out+=bytes([0xDB,a&0xFF])
        elif op=="STDd":  out+=bytes([0xDD,a&0xFF])
        elif op=="ADDDd": out+=bytes([0xD3,a&0xFF])
        elif op=="SUBAd": out+=bytes([0x90,a&0xFF])
        elif op=="ADDB#": out+=bytes([0xCB,a&0xFF])
        # JSR по МЕТКЕ, а не по адресу: подпрограммы лежат в самой рутине и их адрес
        # известен только после раскладки. Расширенный JSR (3 байта) вместо BSR —
        # у BSR смещение ±128, а до интерполятора из начала рутины дальше.
        elif op=="JSRl":  out+=bytes([0xBD,lab[a]>>8,lab[a]&0xFF])
        elif op in OP1:   out+=bytes([OP1[op]])
        else: raise ValueError(op)
        pc=nx
    return out,lab


def main():
    rom=bytearray(open(SRC,"rb").read()); assert len(rom)==32768
    off=lambda a:a-ROM_BASE
    code,lab=asm(ROUT)
    # свободно под рутину и данные
    for a,n in [(ROUT,len(code)),(VEMAP,256),(PAXIS,16),(RAXIS,16),(SMESH,1),(KM,1),(NAKL,1),(KTPS,256),(TAXIS,16),(SPAN,1),(MODE,1)]:
        assert all(b==0x3F for b in rom[off(a):off(a)+n]),"не пусто @ %04X"%a
    # ЕДИНСТВЕННАЯ врезка — на выход заводской таблицы линеаризации расходомера
    ho=off(HOOK)
    assert rom[ho]==0xBD and (rom[ho+1]<<8|rom[ho+2])==ORIG,"по %04X не JSR %04X"%(HOOK,ORIG)
    # 89D8 и B0E5 остаются ЗАВОДСКИМИ: наполнение делит штатный $8057, датчики
    # опрашивает штатный $B148. Проверяем это явно, чтобы остатки прежней схемы
    # не проехали в сборку незамеченными.
    assert (rom[off(0x89D8)+1]<<8|rom[off(0x89D8)+2])==0x8057,"на 89D8 осталась старая врезка"
    assert (rom[off(0xB0E5)+1]<<8|rom[off(0xB0E5)+2])==0xB148,"на B0E5 осталась старая врезка"
    rom[off(ROUT):off(ROUT)+len(code)]=code
    # данные ДАД (номинал)
    # VE — ПОСТРОЕНА ПО ЛОГАМ ПОЛЬЗОВАТЕЛЯ, не выдумана.
    #
    # Формула блока при всех единицах вырождается в Tp = Д, поэтому нужный
    # коэффициент = реальное_наполнение / давление. Обе величины взяты из логов:
    #   холостой   : Tp 23 при 50 кПа   -> 0.46
    #   полный газ : Tp 84…91 при 107 кПа (72 замера, газ >= 80%) -> 0.79…0.85
    # Между ними — линейно по давлению. Главный наклон именно ПО ДАВЛЕНИЮ:
    # разница вдвое, тогда как по оборотам всего ±4%.
    #
    # ⚠ Прошлая версия делала наклон по ОБОРОТАМ и плоско по давлению — это было
    # неверно и давало на холостом вдвое бедно (Tp 11 против нужных 23).
    #
    # Форма по оборотам — из тех же замеров, нормирована на пик 3500 об.
    # Вне 2500…5000 данных нет, поэтому края держим на ближайшем известном.
    # ⚠ ОСИ СТАЛИ РАВНОМЕРНЫМИ (09.08.26). Раньше давление шло шагом 6 от 20, а
    # обороты брались из заводской таблицы $FB20 (неравномерной). Свой поиск берёт
    # номер ячейки СДВИГОМ, поэтому шаг обязан быть степенью двойки. Поверхность
    # VE(давление, обороты) при этом не меняется — она задана формулой ниже и просто
    # считается в новых узлах.
    PAXIS_VAL=[PBASE+PSTEP*i for i in range(16)]     # 16…136 кПа шагом 8
    RAXIS_VAL=[RBASE+RSTEP*i for i in range(16)]     # 8…128 в единицах 51.2 об (410…6554)
    VE_LO,P_LO = 0.46, 50.0        # холостой
    VE_HI,P_HI = 0.83, 107.0       # полный газ (среднее по кривой)
    # ФОРМА ПО ОБОРОТАМ — ИЗМЕРЕНА ШИРОКОПОЛОСНИКОМ 09.08.26, а не выдумана.
    # Прежняя форма была придумана (плоско до 2500, пик на 3500, спад выше) и по факту
    # оказалась перевёрнутой: мотор на холостом переливал (смесь 12.4 при цели 14.5),
    # а к 3000 наоборот беднил (16.0). Ниже — отношение факт/цель по оборотам в зоне
    # 40…60 кПа, где есть замеры, домноженное на прежнюю форму:
    #     об     n     факт/цель
    #    600    82       0.854
    #   1000   449       0.858
    #   1400    40       0.932
    #   1800    47       0.947
    #   2600    15       0.959
    #   3000    22       1.039
    # Точка 2200 (n=12, 0.857) выброшена: соседи по обе стороны дают 0.947 и 0.959,
    # выборка мелкая и почти вся с перегазовок, где широкополосник запаздывает.
    # ⚠ ВЫШЕ 3000 ЗАМЕРОВ НЕТ — форма держится ПЛОСКО. Прежний спад к 5000 (0.928)
    # был выдуман, и на верхах он беднил бы; плоско — в безопасную сторону.
    SHAPE=[(600,0.826),(1000,0.828),(1400,0.898),(1800,0.918),(2600,0.928),
           (3000,1.004),(6500,1.004)]
    def shape(rpm):
        if rpm<=SHAPE[0][0]: return SHAPE[0][1]
        if rpm>=SHAPE[-1][0]: return SHAPE[-1][1]
        for i in range(len(SHAPE)-1):
            (r0,v0),(r1,v1)=SHAPE[i],SHAPE[i+1]
            if r0<=rpm<=r1: return v0+(v1-v0)*(rpm-r0)/(r1-r0)
        return 1.0
    k=(VE_HI-VE_LO)/(P_HI-P_LO)
    for r in range(16):
        s = shape(RAXIS_VAL[r] * 51.2)               # обороты = значение оси × 51.2
        for c in range(16):
            ve = (VE_LO + (PAXIS_VAL[c]-P_LO)*k) * s
            rom[off(VEMAP)+r*16+c] = max(1, min(255, round(ve*128)))
    for i,v in enumerate(PAXIS_VAL): rom[off(PAXIS)+i]=v
    for i,v in enumerate(RAXIS_VAL): rom[off(RAXIS)+i]=v
    rom[off(SMESH)]=26; rom[off(KM)]=128; rom[off(NAKL)]=125
    # данные Ktps: карта 0x80 (=1.0, без поправки), ось TPS из января
    for i in range(256): rom[off(KTPS)+i]=0x80
    for i,v in enumerate(TAXIS_VAL): rom[off(TAXIS)+i]=v
    rom[off(SPAN)]=172        # span полного газа в $14A2 (=344 в $1492)
    rom[off(MODE)]=0          # ПО УМОЛЧАНИЮ РАСХОДОМЕР: без датчика давления ДАД
                              # считал бы мусор. Ставить 1 после установки датчика.
    # адрес врезки: 8965 зовёт нашу рутину вместо заводской таблицы
    rom[ho+1],rom[ho+2]=ROUT>>8,ROUT&0xFF
    # чек-сумма
    s=x=0
    for i in range(len(rom)):
        if i in (0x7F7A,0x7F7B): continue
        s=(s+rom[i])&0xFF; x^=rom[i]
    rom[0x7F7A],rom[0x7F7B]=s,x
    open(DST,"wb").write(rom)
    print("Готово:",os.path.basename(DST))
    print("  рутина %d байт @ C700..%04X"%(len(code),ROUT+len(code)-1))
    print("  ЕДИНСТВЕННАЯ врезка: %04X JSR %04X -> JSR %04X"%(HOOK,ORIG,ROUT))
    print("  89D8 и B0E5 — заводские (проверено при сборке)")
    print("  VE @ C900 | ось давл @ CA00 = %s"%PAXIS_VAL)
    print("  Ktps @ CB00 | ось обор @ CA20 = %s (×51.2 об)"%RAXIS_VAL)
    print("  ось TPS в $14A2:",TAXIS_VAL)
    print("  режим @ %04X = %d (0 расходомер / 1 ДАД)"%(MODE,rom[off(MODE)]))
    print("  чек-сумма: %02X/%02X"%(s,x))


if __name__=="__main__": main()
