# $80CF берёт ось нагрузки из $1482, а режим выборки из $007D. Обе ячейки читают
# ЗАДАЧИ: $8a35 (сглаживание оси карт) и $8b1e (пусковой впрыск). Значит, чтобы
# ими воспользоваться, надо было подменять заводские ячейки и закрывать подмену
# через SEI — прерывания замолкали на 2.1 мс (замерено на двойнике: 1063
# инструкции). Свой поиск не трогает ни $1482, ни $007D, поэтому SEI не нужен,
# ограничение по оборотам снимается, и вся работа снова помещается в один такт.
#
# Оси СВОИ и РАВНОМЕРНЫЕ, поэтому номер ячейки получается сдвигом — ни перебора
# по оси, ни деления для дробной части.
#
# Интерполяция ДВУМЕРНАЯ: по давлению и по оборотам. Сначала было только по давлению,
# и из этого вылезли сразу две неприятности:
#   - индекс строки не мог превысить 14 (байт оборотов упирается в 255), то есть вся
#     шестнадцатая строка карт была недостижима;
#   - чтобы не врать подписью, ось приходилось начинать с нуля — не как у заводских карт;
#   - карта прыгала ступенькой каждые 410 оборотов.
# С интерполяцией по оборотам последняя строка работает как правый конец интервала
# (так же, как последний столбец по давлению), ось снова начинается с 400 как заводская,
# а переход между строками стал плавным.
#
# Ось дросселя у Ktps остаётся январской (неравномерной), там поиск перебором и без
# интерполяции по столбцу — поправка по дросселю к такой тонкости не чувствительна.
# По ОБОРОТАМ Ktps интерполируется наравне с VE, чтобы обе карты понимали свою общую
# ось одинаково.
#
# ================== АРИФМЕТИКА ==================
# Отдаём РАСХОД, а не наполнение. Завод дальше сам поделит на обороты:
#     наполнение = 17.1 × расход ÷ обороты        (снято с 11 режимов из логов,
#                                                  разброс 16.3…17.1)
# Значит:  расход = наполнение × обороты ÷ 17.1,  где наполнение = Д × VE × Ktps × КМ.
# Обороты берём как $140A>>1 (единица = 25.6 об), тогда 25.6/17.1 = 1.497 ≈ 3/256:
#     расход = ((Д·VE·Ktps·КМ × обороты_25.6) >> 8) × 3
# Проверка на замерах: ХХ 800 об, Д=33, VE=0.7 -> 1077 при замеренных 1211;
#                      4800 об, наполнение 73.8 -> 20757 при замеренных 20718.
#
# ПОРЯДОК УМНОЖЕНИЙ ВАЖЕН. Множители перемножаются СНАЧАЛА МЕЖДУ СОБОЙ (они около
# 128, там шаг 1/128), давление домножается ПОСЛЕДНИМ. Если наоборот, после первого
# умножения промежуток на холостом ≈ 23, и ручки Ktps/КМ двигают результат шагами
# 1/23 ≈ 4.3 % — ровно там, где мотор чувствительнее всего.
