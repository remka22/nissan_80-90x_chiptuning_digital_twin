# v44_4 — дочерняя к v44: ТОЛЬКО тарировка нового ДАД, код и карты не тронуты.
#
# Решение пользователя 25.10.26. Старый датчик был сведён к «атмо = 100» при
# настоящей летней ~95, то есть шкала завышена на 5. Сегодня настоящая 97 ->
# на той же шкале должно быть 102. Тогда новый датчик читает в шкале старого,
# и карта VE подходит без пересчёта.
#   наклон 59 — по разности двух точек манометра (40 -> АЦП 58, 170 -> АЦП 624);
#   смещение 24 — на заглушенном моторе АЦП 339 (лог 25.10.26) = 102 кПа.
# Это посередине между v44_1 (19, бедно) и v44_2 (27, «чутка богато»).
#
# Формула блока ($C708, v41): кПа = ((АЦП × $CA11) >> 8) + $CA10, насыщение 255.
import os

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
SRC = os.path.join(ROOT, "логер", "j30_v44_ТЗ-КТЗ-в-кадре-и-ДТВ-20-при-отказе_02.10.26_2146 ИИ.bin")

OFS, SLOPE = 0x4A10, 0x4A11          # $CA10 смещение (кПа), $CA11 наклон (кПа на 256 отсчётов)
OLD = (7, 34)                        # старый датчик, v44
NEW = (24, 59)
ATMO_ADC, ATMO_KPA = 339, 102        # заглушенный мотор сегодня -> старая шкала (+5)


def kpa(adc, ofs, slope):
    return min(255, ((adc * slope) >> 8) + ofs)


def checksum(b):
    s = x = 0
    for i, v in enumerate(b):
        if i in (0x7F7A, 0x7F7B):
            continue
        s = (s + v) & 0xFF
        x ^= v
    b[0x7F7A], b[0x7F7B] = s, x


def build(out_path):
    b = bytearray(open(SRC, "rb").read())
    assert len(b) == 32768
    assert (b[OFS], b[SLOPE]) == OLD, "в исходнике не та тарировка: %d/%d" % (b[OFS], b[SLOPE])
    assert kpa(ATMO_ADC, *NEW) == ATMO_KPA
    b[OFS], b[SLOPE] = NEW
    checksum(b)
    open(out_path, "wb").write(b)


if __name__ == "__main__":
    import sys
    out = sys.argv[1]
    build(out)
    print("смещение $CA10 = %d, наклон $CA11 = %d (v44_1: 19/59, v44_2: 27/59)" % NEW)
    for adc, what in ((58, "40 по манометру"), (338, "атмосфера"), (339, "атмосфера"),
                      (624, "170 по манометру"), (1023, "5 В")):
        print("  АЦП %4d (%s) -> %d кПа" % (adc, what, kpa(adc, *NEW)))
    print("  ловушка $8910: АЦП 32 = %d кПа — ниже блок видит обрыв" % kpa(32, *NEW))
    print("записан:", out)
